    (function initVideoModalSwipe() {
      let touchStartX = 0;
      const videoModalEl = document.getElementById("video-modal");
      if (!videoModalEl) return;
      videoModalEl.addEventListener("touchstart", e => {
        if (e.changedTouches && e.changedTouches.length) {
          touchStartX = e.changedTouches[0].screenX;
        }
      }, { passive: true });
      videoModalEl.addEventListener("touchend", e => {
        if (e.changedTouches && e.changedTouches.length) {
          const diff = e.changedTouches[0].screenX - touchStartX;
          if (Math.abs(diff) > 50) {
            navigateVideoModal(diff < 0 ? 1 : -1);
          }
        }
      }, { passive: true });
    })();

