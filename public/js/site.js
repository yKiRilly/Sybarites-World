    function changeLanguage(lang) {
      if (!translations[lang]) return;
      currentLang = lang;
      try { localStorage.setItem("sybarites_lang", lang); } catch (e) {}
      const dict = translations[lang];

      document.querySelectorAll(".lang-btn").forEach(btn => {
        btn.classList.remove("bg-gold", "text-emerald-deep", "text-[#02310f]", "font-bold", "shadow-md");
        btn.classList.add("text-gold-light/80", "text-gold-light/70");
      });
      const activeHeaderBtn = document.getElementById(`btn-lang-${lang}`);
      if (activeHeaderBtn) {
        activeHeaderBtn.classList.add("bg-gold", "text-[#02310f]", "font-bold");
        activeHeaderBtn.classList.remove("text-gold-light/80", "text-gold-light/70");
      }
      const activeHeroBtn = document.getElementById(`hero-btn-${lang}`);
      if (activeHeroBtn) {
        activeHeroBtn.classList.add("bg-gold", "text-[#02310f]", "font-bold", "shadow-md");
        activeHeroBtn.classList.remove("text-gold-light/80", "text-gold-light/70");
      }

      document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (dict[key]) {
          el.innerHTML = dict[key];
        }
      });

      document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (dict[key]) {
          el.setAttribute("placeholder", dict[key]);
        }
      });

      document.documentElement.lang = lang;
    }

