    function openVideoModal(index) {
      currentVideoIndex = index;
      const v = VIDEOS_DATA[index];
      if (!v) return;
      const player = document.getElementById("modal-video-player");
      player.pause();
      player.src = v.src;
      player.poster = v.poster;
      player.muted = false;
      player.load();
      const prefix = (translations[currentLang] && translations[currentLang].video_label) || "Sybarites World";
      document.getElementById("modal-video-title").textContent = `${prefix} · #${v.id}`;
      const counter = document.getElementById("modal-video-counter");
      if (counter) counter.textContent = `${index + 1} / ${VIDEOS_DATA.length}`;
      document.getElementById("video-modal").classList.remove("hidden");
      document.body.style.overflow = "hidden";
      const playPromise = player.play();
      if (playPromise !== undefined) {
        playPromise.catch(() => {
          player.muted = true;
          player.play().catch(() => {});
        });
      }
    }

    function closeVideoModal() {
      const modal = document.getElementById("video-modal");
      const player = document.getElementById("modal-video-player");
      if (player) {
        player.pause();
        player.removeAttribute("src");
        player.load();
      }
      if (modal) modal.classList.add("hidden");
      document.body.style.overflow = "";
    }

